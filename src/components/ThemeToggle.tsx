"use client";

import { useEffect, useState } from "react";

type Theme = "light" | "dark";

/**
 * Light/dark switch. The actual initial theme is applied before paint by the
 * inline script in layout.tsx (no flash); this component just reflects and
 * toggles it, persisting the choice to localStorage. Dark is the brand default.
 */
export default function ThemeToggle() {
  const [theme, setTheme] = useState<Theme>("dark");
  const [mounted, setMounted] = useState(false);

  useEffect(() => {
    const current =
      (document.documentElement.getAttribute("data-theme") as Theme) || "dark";
    setTheme(current);
    setMounted(true);
  }, []);

  function toggle() {
    const next: Theme = theme === "dark" ? "light" : "dark";
    document.documentElement.setAttribute("data-theme", next);
    try {
      localStorage.setItem("theme", next);
    } catch {
      /* storage unavailable - runtime toggle still works */
    }
    setTheme(next);
  }

  const isDark = theme === "dark";

  return (
    <button
      onClick={toggle}
      aria-label={isDark ? "Switch to light mode" : "Switch to dark mode"}
      title={isDark ? "Switch to light mode" : "Switch to dark mode"}
      className="grid h-9 w-9 place-items-center rounded-lg border border-[var(--hairline)] text-muted transition-colors hover:text-gold"
      // Avoid a hydration mismatch flash: the icon depends on client state.
      suppressHydrationWarning
    >
      {!mounted ? null : isDark ? <MoonIcon /> : <SunIcon />}
    </button>
  );
}

